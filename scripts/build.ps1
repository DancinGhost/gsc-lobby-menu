<#
.SYNOPSIS
    Build the lobby menu for each game.

.DESCRIPTION
    Assembles src/<game>/mp/lobbymenu_<game>_mp.gsc + src/common/*.gsc into
    build/<game>/mp/lobbymenu_<game>_mp.gsc. Plutonium loads this source file directly.

    -Compile             Also compile with gsc-tool to catch errors before launching the
                         game. Output: build/compiled/<game>/mp/. IW5 requires local
                         #include files in -Iw5IncludeDir for full compilation; without
                         it IW5 is syntax-checked only (parse mode).
    -InstallToPlutonium  Copy the build into <storage>\<game>\scripts\mp\. Installs the
                         compiled file when -Compile was given, the source otherwise.
    -PlutoniumStorage    Storage folder (default: %LOCALAPPDATA%\Plutonium\storage).

.EXAMPLE
    .\scripts\build.ps1 -Game all -InstallToPlutonium
#>
param(
    [ValidateSet("all", "t6", "iw5")]
    [string]$Game = "all",
    [switch]$Compile,
    [string]$GscToolPath = "gsc-tool.exe",
    [string]$Iw5IncludeDir = $env:IW5_INCLUDE_DIR,
    [switch]$InstallToPlutonium,
    [string]$PlutoniumStorage = ""
)

$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$BuildRoot = Join-Path $RepoRoot "build"

if ($InstallToPlutonium -and -not $PlutoniumStorage) {
    if (-not $env:LOCALAPPDATA) {
        throw "Could not determine default Plutonium storage path (LOCALAPPDATA is unset). Pass -PlutoniumStorage."
    }
    $PlutoniumStorage = Join-Path $env:LOCALAPPDATA "Plutonium\storage"
}

if ($Compile) {
    $GscToolCmd = Get-Command $GscToolPath -ErrorAction SilentlyContinue
    if (-not $GscToolCmd) {
        throw "Could not find '$GscToolPath'. Download gsc-tool from https://github.com/xensik/gsc-tool/releases and add it to PATH or pass -GscToolPath."
    }
    $GscToolPath = $GscToolCmd.Source
}

function Get-ScriptName([string]$GameId) {
    return "lobbymenu_${GameId}_mp.gsc"
}

function Invoke-Assemble([string]$GameId) {
    $Name = Get-ScriptName $GameId
    $Entry = Join-Path $RepoRoot "src/$GameId/mp/$Name"
    if (-not (Test-Path $Entry)) { throw "Missing entry file $Entry" }

    $OutDir = Join-Path $BuildRoot "$GameId/mp"
    New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
    Remove-Item -Force -ErrorAction SilentlyContinue (Join-Path $BuildRoot "compiled/$GameId/mp/$Name")
    $Out = Join-Path $OutDir $Name

    $Parts = @("// GENERATED by scripts/build.ps1 - do not edit. Sources: src/$GameId/mp/$Name, src/common/*.gsc", "")
    $Parts += Get-Content -Raw $Entry
    foreach ($File in Get-ChildItem (Join-Path $RepoRoot "src/common") -Filter *.gsc | Sort-Object Name) {
        $Parts += ""
        $Parts += "// ---- src/common/$($File.Name) ----"
        $Parts += ""
        $Parts += Get-Content -Raw $File.FullName
    }

    # Plain UTF-8 without BOM so the game's script parser doesn't see stray bytes.
    [System.IO.File]::WriteAllText($Out, ($Parts -join "`n"), (New-Object System.Text.UTF8Encoding $false))
    Write-Host "[$GameId] Assembled -> $Out" -ForegroundColor Cyan
}

# gsc-tool writes to .\compiled\<game>\ under its working directory, so run it in a temp folder.
function Invoke-Compile([string]$GameId) {
    $Name = Get-ScriptName $GameId
    $Work = Join-Path ([System.IO.Path]::GetTempPath()) ("lobbymenu-" + [guid]::NewGuid())
    New-Item -ItemType Directory -Force -Path $Work | Out-Null

    try {
        Copy-Item (Join-Path $BuildRoot "$GameId/mp/$Name") (Join-Path $Work $Name)

        $Mode = "comp"
        $ToolArgs = @()
        if ($GameId -eq "iw5") {
            if ($Iw5IncludeDir) {
                if (-not (Test-Path (Join-Path $Iw5IncludeDir "maps"))) { throw "Iw5IncludeDir has no maps\ folder: $Iw5IncludeDir" }
                $ToolArgs += @("-w", (Resolve-Path $Iw5IncludeDir).Path)
            } else {
                $Mode = "parse"
                Write-Warning "[$GameId] -Iw5IncludeDir not set; parsing only (no include/builtin resolution)."
            }
        }

        Write-Host "[$GameId] gsc-tool -m $Mode ..." -ForegroundColor Cyan
        Push-Location $Work
        try {
            & $GscToolPath -m $Mode -g $GameId -s pc @ToolArgs $Name
            if ($LASTEXITCODE -ne 0) { throw "[$GameId] gsc-tool failed (exit code $LASTEXITCODE)" }
        } finally {
            Pop-Location
        }

        if ($Mode -ne "comp") { return }

        $Built = Get-ChildItem (Join-Path $Work "compiled") -Recurse -File -ErrorAction SilentlyContinue |
            Where-Object { $_.Name -eq $Name -or $_.Name -eq ([System.IO.Path]::ChangeExtension($Name, ".gscbin")) } |
            Select-Object -First 1
        if (-not $Built) { throw "[$GameId] gsc-tool reported success but wrote no output under $Work\compiled" }

        $OutDir = Join-Path $BuildRoot "compiled/$GameId/mp"
        New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
        Copy-Item -Force $Built.FullName (Join-Path $OutDir $Name)
        Write-Host "[$GameId] Compiled -> $(Join-Path $OutDir $Name)" -ForegroundColor Green
    } finally {
        Remove-Item -Recurse -Force $Work -ErrorAction SilentlyContinue
    }
}

function Invoke-Install([string]$GameId) {
    $Name = Get-ScriptName $GameId
    $From = Join-Path $BuildRoot "$GameId/mp/$Name"
    $CompiledFile = Join-Path $BuildRoot "compiled/$GameId/mp/$Name"
    if ($Compile -and (Test-Path $CompiledFile)) { $From = $CompiledFile }

    $Dest = Join-Path $PlutoniumStorage "$GameId\scripts\mp"
    New-Item -ItemType Directory -Force -Path $Dest | Out-Null
    Copy-Item -Force $From (Join-Path $Dest $Name)
    Write-Host "[$GameId] Installed -> $(Join-Path $Dest $Name)" -ForegroundColor Yellow
}

$Games = if ($Game -eq "all") { @("t6", "iw5") } else { @($Game) }

foreach ($GameId in $Games) {
    Invoke-Assemble $GameId
    if ($Compile) { Invoke-Compile $GameId }
    if ($InstallToPlutonium) { Invoke-Install $GameId }
}
