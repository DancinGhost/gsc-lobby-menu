#!/usr/bin/env bash
#
# Build the lobby menu for each game.
#
# Usage: scripts/build.sh [all|t6|iw5]... [--compile] [--install] [--storage DIR]
#
#   (default)      Assemble src/<game>/mp/lobbymenu_<game>_mp.gsc + src/common/*.gsc
#                  into build/<game>/mp/lobbymenu_<game>_mp.gsc. Plutonium loads this
#                  source file directly.
#   --compile      Also compile with gsc-tool ($GSC_TOOL, default "gsc-tool") to catch
#                  errors before launching the game. Output: build/compiled/<game>/mp/.
#                  IW5 requires local #include files in $IW5_INCLUDE_DIR for full
#                  compilation; without it IW5 is syntax-checked only (parse mode).
#   --install      Copy the build into <storage>/<game>/scripts/mp/. Installs the
#                  compiled file when --compile was given, the source otherwise.
#   --storage DIR  Plutonium storage folder (implies --install). Defaults to
#                  $PLUTONIUM_STORAGE, then the default Wine prefix location.
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
BUILD_ROOT="$REPO_ROOT/build"
GSC_TOOL="${GSC_TOOL:-gsc-tool}"
IW5_INCLUDE_DIR="${IW5_INCLUDE_DIR:-}"

GAMES=()
COMPILE=0
INSTALL=0
STORAGE="${PLUTONIUM_STORAGE:-}"

usage() {
  sed -n '5,17p' "$0" | sed 's/^# \{0,1\}//'
}

die() {
  echo "error: $*" >&2
  exit 1
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    all) GAMES=(t6 iw5) ;;
    t6|iw5) GAMES+=("$1") ;;
    --compile) COMPILE=1 ;;
    --install) INSTALL=1 ;;
    --storage)
      [[ $# -ge 2 ]] || die "--storage needs a directory"
      STORAGE="$2"
      INSTALL=1
      shift
      ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; die "unknown argument '$1'" ;;
  esac
  shift
done

if [[ ${#GAMES[@]} -eq 0 ]]; then
  GAMES=(t6 iw5)
fi

assemble() {
  local game="$1"
  local name="lobbymenu_${game}_mp.gsc"
  local entry="$REPO_ROOT/src/$game/mp/$name"
  local out_dir="$BUILD_ROOT/$game/mp"
  local out="$out_dir/$name"

  [[ -f "$entry" ]] || die "missing entry file $entry"
  mkdir -p "$out_dir"
  rm -f "$BUILD_ROOT/compiled/$game/mp/$name"

  {
    printf '// GENERATED by scripts/build.sh - do not edit. Sources: src/%s/mp/%s, src/common/*.gsc\n\n' "$game" "$name"
    cat "$entry"
    local f
    for f in "$REPO_ROOT"/src/common/*.gsc; do
      printf '\n// ---- %s ----\n\n' "${f#"$REPO_ROOT"/}"
      cat "$f"
    done
  } > "$out"

  echo "[$game] Assembled -> ${out#"$REPO_ROOT"/}"
}

# Runs gsc-tool in a scratch directory (it writes to ./compiled/<game>/) and
# fails on a non-zero exit code or a missing output file.
compile() {
  local game="$1"
  local name="lobbymenu_${game}_mp.gsc"
  local src="$BUILD_ROOT/$game/mp/$name"
  local work
  work="$(mktemp -d)"
  # shellcheck disable=SC2064
  trap "rm -rf '$work'; trap - RETURN EXIT" RETURN EXIT

  cp "$src" "$work/$name"

  local mode="comp"
  local args=()
  if [[ "$game" == "iw5" ]]; then
    if [[ -n "$IW5_INCLUDE_DIR" ]]; then
      [[ -d "$IW5_INCLUDE_DIR/maps" ]] || die "IW5_INCLUDE_DIR has no maps/ folder: $IW5_INCLUDE_DIR"
      args+=(-w "$(cd "$IW5_INCLUDE_DIR" && pwd)")
    else
      mode="parse"
      echo "[$game] IW5_INCLUDE_DIR not set; parsing only (no include/builtin resolution)."
    fi
  fi

  echo "[$game] gsc-tool -m $mode ..."
  if ! (cd "$work" && "$GSC_TOOL" -m "$mode" -g "$game" -s pc "${args[@]+"${args[@]}"}" "$name"); then
    die "[$game] gsc-tool failed"
  fi

  [[ "$mode" == "comp" ]] || return 0

  local built
  built="$(find "$work/compiled" -type f \( -name "${name%.gsc}.gscbin" -o -name "$name" \) 2>/dev/null | head -n 1)"
  [[ -n "$built" ]] || die "[$game] gsc-tool reported success but wrote no output under $work/compiled"

  local out_dir="$BUILD_ROOT/compiled/$game/mp"
  mkdir -p "$out_dir"
  cp "$built" "$out_dir/$name"
  echo "[$game] Compiled -> ${out_dir#"$REPO_ROOT"/}/$name"
}

default_storage() {
  local candidate="${WINEPREFIX:-$HOME/.wine}/drive_c/users/$USER/AppData/Local/Plutonium/storage"
  [[ -d "$candidate" ]] && echo "$candidate"
  return 0
}

install_game() {
  local game="$1"
  local name="lobbymenu_${game}_mp.gsc"
  local from="$BUILD_ROOT/$game/mp/$name"
  if [[ "$COMPILE" -eq 1 && -f "$BUILD_ROOT/compiled/$game/mp/$name" ]]; then
    from="$BUILD_ROOT/compiled/$game/mp/$name"
  fi

  local dest="$STORAGE/$game/scripts/mp"
  mkdir -p "$dest"
  cp "$from" "$dest/$name"
  echo "[$game] Installed -> $dest/$name"
}

if [[ "$INSTALL" -eq 1 && -z "$STORAGE" ]]; then
  STORAGE="$(default_storage)"
  [[ -n "$STORAGE" ]] || die "no Plutonium storage folder found; pass --storage DIR or set PLUTONIUM_STORAGE"
fi

if [[ "$COMPILE" -eq 1 ]]; then
  RESOLVED_GSC_TOOL="$(command -v "$GSC_TOOL" 2>/dev/null || true)"
  [[ -n "$RESOLVED_GSC_TOOL" ]] || die "'$GSC_TOOL' not found. Get it from https://github.com/xensik/gsc-tool/releases or set GSC_TOOL=/path/to/gsc-tool"
  [[ "$RESOLVED_GSC_TOOL" == /* ]] || RESOLVED_GSC_TOOL="$PWD/$RESOLVED_GSC_TOOL"
  GSC_TOOL="$RESOLVED_GSC_TOOL"
fi

for game in "${GAMES[@]}"; do
  assemble "$game"
  if [[ "$COMPILE" -eq 1 ]]; then
    compile "$game"
  fi
  if [[ "$INSTALL" -eq 1 ]]; then
    install_game "$game"
  fi
done
